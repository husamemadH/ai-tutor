"""Ingest a clean Arabic sample book (bypasses PDF extraction) for end-to-end testing."""

from ai_tutor.db import session_scope
from ai_tutor.ingest.parse import Page
from ai_tutor.ingest.pipeline import ingest_pages

PAGES = [
    Page(
        1,
        "الخلية\n\n"
        "الخلية هي وحدة البناء الأساسية في جميع الكائنات الحية. تحتوي الخلية على غشاء "
        "يحيط بها ويحمي محتوياتها. داخل الخلية توجد أجزاء صغيرة تقوم بوظائف مختلفة.\n\n"
        "الخلية النباتية تختلف عن الخلية الحيوانية، لأن الخلية النباتية تحتوي على "
        "البلاستيدات الخضراء التي تساعد النبات على صنع غذائه.\n\n"
        "النواة\n\n"
        "النواة هي مركز التحكم في الخلية. تحتوي النواة على المادة الوراثية التي تحمل "
        "صفات الكائن الحي. النواة تتحكم بجميع أنشطة الخلية ووظائفها.",
    ),
    Page(
        2,
        "البناء الضوئي\n\n"
        "البناء الضوئي هي العملية التي يصنع فيها النبات غذاءه بنفسه. يحتاج النبات في "
        "هذه العملية إلى ضوء الشمس والماء وثاني أكسيد الكربون.\n\n"
        "ينتج عن عملية البناء الضوئي سكر الجلوكوز، وهو غذاء النبات، وينتج أيضا غاز "
        "الأكسجين الذي يحتاجه الإنسان والحيوان للتنفس.\n\n"
        "دورة الماء\n\n"
        "تتبخر المياه من البحار والأنهار بفعل حرارة الشمس. يتصاعد بخار الماء إلى الأعلى "
        "ثم يبرد ويتكاثف مكونا السحاب. عندما تثقل السحب يسقط المطر.",
    ),
]


def main() -> None:
    with session_scope() as db:
        book, count = ingest_pages(
            db,
            pages=PAGES,
            grade="4",
            subject="العلوم",
            title="العلوم للصف الرابع (عينة)",
            file_path="sample://science-grade4",
        )
    print(f"ingested {book.id} '{book.title}' -> {count} chunks")


if __name__ == "__main__":
    main()