_HISTORY_NOTE_JO = "\n\nهاي محادثة مستمرة، فتذكّر شو الطالب سأل قبل وكمّل عليه."
_HISTORY_NOTE_MSA = "\n\nهذه محادثة مستمرة، فتذكّر ما سأل عنه الطالب سابقاً وابنِ عليه."

_MATH_NOTATION = """\


الترميز الرياضي:
- حافظ على أسماء المتغيرات والمعاملات والرموز الرياضية ونمط الأرقام كما وردت في المسألة ومقتطفات الكتاب. إذا استخدم الكتاب x وa وb وc، فاستعملها نفسها ولا تستبدل بها س وأ وب وج؛ وإذا استخدم رموزاً عربية، فلا تحوّلها إلى حروف لاتينية.
- عند حل معادلة كتبها الطالب، حافظ على متغيراتها كما كتبها، حتى إن اختلفت عن رموز المثال في الكتاب. لا تغيّر أسماء المتغيرات أثناء خطوات الحل أو في سؤال التأكد.
- في الأمثلة الجديدة وأسئلة التأكد، اتبع ترميز المسألة التي تشرحها أو ترميز الكتاب إن لم يقدّم الطالب مسألة. يمكن تنسيق المعادلات باستخدام LaTeX، لكن التنسيق لا يبرّر تغيير رموزها."""


def _format_chunk(chunk: Chunk) -> str:
    page = chunk.display_page
    location = f"صفحة {page}" if page else "بدون رقم صفحة"
    if chunk.section:
        location = f"{location} - {chunk.section}"
    return f"[{location}]\n{chunk.content}"


def build_system_prompt(
    *,
    grade: str,
    subject: str,
    book_title: str | None,
    chunks: list[Chunk],
) -> str:
    instruction = (
        _INSTRUCTIONS_MSA if get_settings().tutor_dialect == "msa" else _INSTRUCTIONS_JO
    ).format(grade=grade, subject=subject)
    history_note = (
        _HISTORY_NOTE_MSA if get_settings().tutor_dialect == "msa" else _HISTORY_NOTE_JO
    )
    book = book_title or "الكتاب المحدد"
    if chunks:
        context = "\n\n".join(_format_chunk(chunk) for chunk in chunks)
    else:
        context = "(ما في مقتطفات متاحة من الكتاب لهذا السؤال)"
    return (
        f"{instruction}{_MATH_NOTATION}{history_note}\n\n"
        f"## مقتطفات الكتاب: {book}\n\n{context}"
    )
